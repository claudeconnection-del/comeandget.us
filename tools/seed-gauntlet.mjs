// Deterministically (re)write every gauntlet artifact from the four fragments in
// secret/gauntlet.json (gitignored). Idempotent: same fragments -> byte-identical
// output, so the repo stays diff-clean. Run: npm run seed:gauntlet.
//
// What ships (all committed): the reworked check-in.json JWT, the introspection
// JSON, the stego PNG, the AES-GCM ciphertext, the final instruction file, and the
// generated middleware manifest. What never ships: FR4 (DNS-only) and the riddle
// answer (lives in the _rabbit TXT record, off-repo). The ciphertext decrypts only
// to the *instruction* to go dig _rabbit — never to an answer.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { deriveKeyHex, pathHash, hex } from "./gauntlet-derive.mjs";
import { seal } from "./gauntlet-crypto.mjs";
import { makeStegoPng } from "./png-stego.mjs";

const FR = JSON.parse(readFileSync("secret/gauntlet.json", "utf8"));
const b64url = (s) => Buffer.from(String(s), "utf8").toString("base64url");
const writeSite = (p, data) => writeFileSync("site" + p, data);

const keyHex = await deriveKeyHex(FR, FR.order, FR.sep);
const introspectPath = `/root/.well-known/${await pathHash("introspect:" + FR.FR2)}.json`;
const pngPath = `/root/a/${await pathHash("png:" + FR.FR2 + FR.FR3)}.png`;
const sealPath = `/root/a/${await pathHash("seal:" + keyHex)}.txt`;
const finalPath = `/root/a/${await pathHash("open:" + keyHex)}.txt`;

mkdirSync("site/root/.well-known", { recursive: true });
mkdirSync("site/root/a", { recursive: true });

// ---- G1: the header breadcrumb (real trail + shard-1) ----------------------
const headerText = `GET ./check-in.json — mind the alg. shard-1:${FR.FR1}`;
const HEADER_HEX = hex(headerText);

// ---- G1 artifact: check-in.json with a reworked alg:none JWT ---------------
// The JWT no longer names DNS. FR2 hides in a cnf.kid claim; the `next` claim
// tells the solver to hash it into the introspection path. `motd` is base64.
const jwtHeader = b64url(JSON.stringify({ alg: "none", typ: "JWT" }));
const jwtPayload = b64url(JSON.stringify({
  iss: "https://sts.windows.net/00000000-0000-0000-0000-000000000000/",
  aud: "https://graph.microsoft.com",
  appid: "1b730954-1685-4b74-9bfd-dac224a7b894",
  scp: "Directory.ReadWrite.All",
  roles: ["Global Administrator"],
  note: "alg:none — we did not sign this, and nobody checked",
  cnf: { kid: FR.FR2 },
  next: "sha256('introspect:' + kid), first 16 hex, served under /root/.well-known/<that>.json",
}));
writeSite("/root/check-in.json", JSON.stringify({
  schema: "intune.deviceCheckin/v2",
  deviceName: "NEO-WS01",
  entraDeviceId: "7f3a1c20-9b4e-4c2a-bf21-0d11e9a7c655",
  joinType: "Entra joined",
  managedBy: "Intune (MDM)",
  ownership: "Corporate",
  complianceState: "noncompliant",
  osVersion: "Windows 11 Pro 23H2 (22631.4317)",
  lastSync: "1970-01-01T00:00:00Z",
  userPrincipalName: "neo@comeandget.onmicrosoft.com",
  assignedRoles: ["Global Administrator"],
  tenantId: "00000000-0000-0000-0000-000000000000",
  notes: "token replay observed from a new location. do not revoke. observe.",
  motd: b64url("decode the _token. mind the alg. the kid is a shard; the 'next' claim says where it points."),
  _token: `${jwtHeader}.${jwtPayload}.`,
}, null, 2) + "\n");

// ---- G2 artifact: introspection JSON points at the PNG ---------------------
writeSite(introspectPath, JSON.stringify({
  sub: "device-introspection",
  status: "noncompliant",
  attestation: `the compliance evidence is an image: ${pngPath}. read what is written in it — not what it shows.`,
}, null, 2) + "\n");

// ---- G3 artifact: stego PNG (real tEXt fragment + decoy LSB) ----------------
const pngText =
  `shard-3:${FR.FR3} · sealed instruction at ${sealPath} · ` +
  `key = sha256(shard-1:shard-2:shard-3:shard-4). ` +
  `shard-4 is not here — dig TXT _shard.comeandget.us`;
writeSite(pngPath, makeStegoPng({ width: 96, height: 64, text: pngText, decoy: "ashfall" }));

// ---- G4 artifacts: ciphertext + the final (fixed) instruction --------------
writeSite(sealPath, (await seal(keyHex, finalPath)) + "\n");
writeSite(finalPath,
  "dig TXT _rabbit.comeandget.us — decode the record, then answer the riddle in the subject line to please@comeandget.us\n");

// ---- The middleware manifest (generated, committed) ------------------------
writeFileSync("functions/root/_gates.js",
`// GENERATED by tools/seed-gauntlet.mjs — do not edit by hand. Re-run: npm run seed:gauntlet.
// Import-only (leading underscore keeps Pages from routing it as an endpoint).
export const HEADER_HEX = ${JSON.stringify(HEADER_HEX)};
export const GATE_PATHS = ${JSON.stringify({
  "/root/check-in.json": "g1",
  [introspectPath]: "g2",
  [pngPath]: "g3",
  [sealPath]: "g4seal",
  [finalPath]: "g4open",
}, null, 2)};
`);

console.log("seeded gauntlet:");
console.log("  G2 introspection:", introspectPath);
console.log("  G3 png:          ", pngPath);
console.log("  G4 sealed:       ", sealPath);
console.log("  G4 final:        ", finalPath);
